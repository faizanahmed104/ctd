export const getFuelTypes = (categoryValue) => {
  if (!categoryValue) return [];
  const categoryKey = CATEGORY_MAP[categoryValue];
  const categoryData = DATA[categoryKey];
  if (!categoryData) return [];
  
  return categoryData.fuelTypes.map(type => ({
    value: type.toLowerCase().replace(/[\s()/.=*-]+/g, '-'),
    label: type
  }));
};

